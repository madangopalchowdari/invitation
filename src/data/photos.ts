export const photos: WeddingPhoto[] = entries.map(
  ([id, category, portrait, x, y, priority, recommendedScene, alt]) => ({
    id,
    src: `/photos/${id}.webp`,
    category,
    aspectRatio: portrait ? 2 / 3 : 3 / 2,
    focalPoint: { x, y },
    dominantColors:
      id === "KP-03"
        ? ["#41413d", "#b0aeaa"]
        : ["#a8d7b6", "#64273c", "#395433", "#bd964d"],
    recommendedScene,
    orientation: portrait ? "portrait" : "landscape",
    priority,
    alt,
  }),
);

export const photoFor = (scene: string) =>
  photos.find((photo) => photo.recommendedScene === scene)!;

